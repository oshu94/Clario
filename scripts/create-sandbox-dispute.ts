/**
 * Script: create-sandbox-dispute
 * 
 * Usage:
 *   node --experimental-strip-types scripts/create-sandbox-dispute.ts <BUYER_TRANSACTION_ID> <BUYER_EMAIL> [REASON] [AMOUNT] [CURRENCY]
 * 
 * Or via environment variables:
 *   BUYER_TRANSACTION_ID, BUYER_EMAIL, REASON, AMOUNT, CURRENCY
 */

import {
  createSandboxDispute,
  getDisputeDetails,
  requireSellerEvidence,
  getPayPalCredentials,
} from '../src/lib/paypal-client.ts';

async function main() {
  console.log('=== DISPUTEREADY: PayPal Sandbox Dispute Creator ===');

  const creds = getPayPalCredentials();
  if (!creds) {
    console.error('\n[BLOCKED] Missing PayPal credentials.');
    console.error('Please configure PAYPAL_CLIENT_ID and PAYPAL_CLIENT_SECRET in your environment or .env file.');
    process.exit(1);
  }

  const buyerTxId = process.argv[2] || process.env.BUYER_TRANSACTION_ID;
  const buyerEmail = process.argv[3] || process.env.BUYER_EMAIL;
  const reason = process.argv[4] || process.env.REASON || 'MERCHANDISE_OR_SERVICE_NOT_RECEIVED';
  const amountVal = process.argv[5] || process.env.AMOUNT || '25.00';
  const currency = process.argv[6] || process.env.CURRENCY || 'USD';

  if (!buyerTxId || !buyerEmail) {
    console.log('\nUsage:');
    console.log('  node --experimental-strip-types scripts/create-sandbox-dispute.ts <BUYER_TRANSACTION_ID> <BUYER_EMAIL> [REASON] [AMOUNT] [CURRENCY]\n');
    console.log('Parameters:');
    console.log('  BUYER_TRANSACTION_ID : Real transaction ID generated by buyer sandbox payment');
    console.log('  BUYER_EMAIL          : Sandbox personal buyer account email');
    console.log('  REASON               : e.g. MERCHANDISE_OR_SERVICE_NOT_RECEIVED, MERCHANDISE_OR_SERVICE_NOT_AS_DESCRIBED');
    console.log('  AMOUNT               : e.g. 25.00 (must be <= transaction amount)');
    console.log('  CURRENCY             : default USD\n');
    console.log('Manual Buyer Steps Required:');
    console.log('  1. Log into https://sandbox.paypal.com with personal sandbox buyer account.');
    console.log('  2. Send money or pay the sandbox business account.');
    console.log('  3. In Buyer Activity, copy the Transaction ID (e.g. 8AA1234567890123C).');
    console.log('  4. Run this script with the copied Transaction ID.');
    process.exit(0);
  }

  console.log(`\nAttempting sandbox dispute creation for buyer: ${buyerEmail.replace(/(?<=.{2}).(?=.*@)/g, '*')}`);
  console.log(`Transaction ID: ${buyerTxId.slice(0, 4)}...${buyerTxId.slice(-4)}`);
  console.log(`Reason: ${reason}`);
  console.log(`Amount: ${amountVal} ${currency}`);

  try {
    const disputeResponse = await createSandboxDispute({
      buyerTransactionId: buyerTxId,
      buyerEmail,
      reason,
      disputeAmount: { currency_code: currency, value: amountVal },
    });

    console.log('\n[SUCCESS] Sandbox dispute created successfully!');
    console.log(`Dispute ID: ${disputeResponse.dispute_id || disputeResponse.id}`);

    const disputeId = disputeResponse.dispute_id || disputeResponse.id;

    // Check if dispute is UNDER_REVIEW and require evidence can be triggered
    console.log('\nInspecting initial dispute state...');
    const details = await getDisputeDetails(disputeId);
    console.log(`Current Status: ${details.status}`);
    console.log(`Lifecycle Stage: ${details.dispute_life_cycle_stage || 'N/A'}`);

    const hasRequireEvidence = details.links?.some((l) => l.rel === 'require-evidence');

    if (details.status === 'UNDER_REVIEW' && hasRequireEvidence) {
      console.log('Dispute is UNDER_REVIEW with require-evidence link present. Advancing to WAITING_FOR_SELLER_RESPONSE...');
      await requireSellerEvidence(disputeId);
      console.log('[SUCCESS] Dispute state transitioned to WAITING_FOR_SELLER_RESPONSE. Ready for seller evidence submission!');
    } else {
      console.log(`Status is ${details.status}. Evidence submission link will be available once transitioned to WAITING_FOR_SELLER_RESPONSE.`);
    }
  } catch (error: any) {
    console.error('\n[CREATION FAILED]:', error.message);
    if (error.message.includes('PAYPAL_PERMISSION_DENIED') || error.message.includes('DISPUTE_CREATE')) {
      console.error('\nScope Blocker Notice:');
      console.error('The sandbox client lacks buyer-side "DISPUTE_CREATE" scope.');
      console.error('Per official PayPal guidelines, merchant-side inspection and evidence submission can proceed');
      console.error('using existing sandbox disputes or verified fallback test fixtures.');
    }
    process.exit(1);
  }
}

main().catch((err) => {
  console.error('Unexpected error:', err);
  process.exit(1);
});
